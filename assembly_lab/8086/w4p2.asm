; FIBONACII SERIES
ASSUME CS:CODE, DS:DATA
DATA SEGMENT
        NUM1 DB "ENTER THE NUMBER: $"
        TEMP DB ?
        FIBARR DB 10 DUP(0)
DATA ENDS
CODE SEGMENT
        MOV AX, DATA
        MOV DS, AX

        MOV SI,OFFSET FIBARR
        LEA DX,NUM1
        MOV AH,09H  ; DISPLAY OF THE STRING
        INT 21H

        MOV AH,01H  ; TO READ THE INPUT FROM THE DEBUG WINDOW
        INT 21H
        
       SUB AL,30H  ; INPUT IS IN ASCII CODE, TO CONVERT INTO DECIMAL NUMBER
                    ; ASCII CODE FOR DECIMAL NUMBERS: 30H TO 39H
        MOV CL,AL   ; INITIALIZING THE CL(COUNT) REGISTER WITH THE GIVEN NUMBER

        MOV AL,00   ; FIRST NUMBER OF FIBONACII SERIES LOADED INTO AL
        MOV [SI],AL ; MOVING INTO THE MEMORY
        ADD AL,30H ; CONVERTING THE NUMBER TO ASCII CODE
        MOV DL,AL    ;...?
        MOV AH,02H  ; TO DISPLAY THE NUMBER IN DEBUG MODE
        INT 21H

        MOV AL,01H      ; INCREMENTING THE AL TO GET THE 2ND NUMBER OF FIBONACII SERIES
        MOV [SI+1],AL

                            
        ADD AL,30H ; CONVERTING THE NUMBER TO ASCII CODE
        MOV DL,AL    ;...?
        MOV AH,02H  ; TO DISPLAY THE NUMBER IN DEBUG MODE
        INT 21H


    LBL1: MOV AL,[SI]
          ADD AL,[SI+1]
          MOV [SI+2],AL
          ADD AL,30H
          MOV DL,AL
          MOV AH,02H
          INT 21H
          INC SI
          
          LOOP LBL1
          MOV AH,4CH
          INT 21H
CODE ENDS
END
