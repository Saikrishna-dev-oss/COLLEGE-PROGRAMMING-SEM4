ASSUME CS:CODE, DS:DATA
DATA SEGMENT
        ARR DB 0A5H, 56H, 67H
DATA ENDS

CODE SEGMENT
        MOV AX, DATA
        MOV DS, AX

        MOV SI, OFFSET ARR      ; USING DIRECTIVE
                                 ; ALTERNATIVE USING INSTRUCTION: LEA SI, ARR
        MOV CL, 02H     ; NO. OF COMPARISONS (N-1): N: NUMBER OF ELEMENTS

        MOV AL, [SI]    ; LOADING THE FIRST ELEMENT OF [SI]
        INC SI          ; INCREMENTING THE SI TO THE NEXT ELEMENT

   BACK:MOV BL, [SI]    ; MOVING THE ELEMENT OF [SI] INTO BL
        CMP AL, BL      ; COMPARING AL AND BL ELEMENTS 
        JA GO   ; JA  JUMP IF ABOVE USED FOR UNSIGNED NUMBERS 
                     ; JG JUMP IF GREATER USED FOR SIGNED NUMBERS 
        XCHG AL, BL     ; IF AL < BL EXCHANGE THE CONTENT SUCH THAT
                        ; AL IS ALWAYS HAVING BIGGER NUMBER

     GO:INC SI          ; INCREMENT THE POSITION TO THE NEXT ELEMENT
        DEC CL          ; DECREMENT COUNTER      
        JNZ BACK        ; IF CL!= 0 REPEAT THE PROCESS 
        MOV [SI], AL    ; STORING THE RESULT INTO MEMORY

        INT 03H ;SIGNIFIES BREAKPOINT, HALTING PROGRAM EXECUTION AND
                ;TRANSFERRING CONTROL TO THE DEBUGGER
CODE ENDS
END
